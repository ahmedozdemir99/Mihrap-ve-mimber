function resource(name: 'Cuma' | 'Bayram') {
  const base = `${directory}/${name}%20Hutbesi%20Dualar%C4%B1`;
  return {
    pdf: `${base}.pdf`,
    recording: {
      name: `${name} hutbesi duaları · Diyanet’in sesli okuması`,
      url: `${base}-mp4-.mp4`,
      fallback: HUTBE_SOURCE_PAGE,
      video: true,
    } satisfies MediaItem,
  };
}

